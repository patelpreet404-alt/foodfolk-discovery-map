import { test, expect } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'

test('live city search and device-location flow retrieve genuine restaurants', async ({ page, context }) => {
  test.skip(process.env.LIVE_DISCOVERY !== '1', 'Explicit opt-in avoids unnecessary public provider requests.')
  test.setTimeout(150000)
  mkdirSync('../.impeccable/review/discovery', { recursive: true })
  const responses: {url: string; status: number}[] = []
  const errors: string[] = []
  page.on('response', response => {if (/photon|overpass|wikipedia|wikimedia/.test(response.url())) responses.push({ url: response.url().split('?')[0], status: response.status() })})
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#around-your-table')
  const section = page.locator('#around-your-table')
  await page.getByLabel('Choose a city', { exact: true }).fill('London')
  await page.getByRole('button', { name: 'Search cities', exact: true }).click()
  await page.getByRole('button', { name: 'London, England, United Kingdom', exact: true }).click({timeout:30000})
  await expect(section.locator('.restaurant-story h3')).toBeVisible({timeout:45000})
  await expect(section.locator('.culinary-fact > a')).toBeVisible({timeout:45000})
  const first = await section.locator('.restaurant-story h3').innerText()
  await expect(section.getByRole('link', {name:/Explore restaurant/})).toHaveAttribute('href', /^https:\/\//)
  await section.screenshot({path:'../.impeccable/review/discovery/live-london.png'})
  await section.getByRole('button',{name:'Next restaurant',exact:true}).click()
  await expect(section.locator('.restaurant-story h3')).not.toHaveText(first)
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({latitude:51.5074456,longitude:-0.1277653,accuracy:150})
  await section.getByRole('button',{name:'Discover near me',exact:true}).click()
  await expect(section.locator('.restaurant-story h3')).toBeVisible({timeout:45000})
  await expect(section.locator('.restaurant-distance-note')).toContainText('your approximate location')
  await expect(section).not.toContainText('51.507')
  await expect(section).not.toContainText('-0.128')
  const stored = await page.evaluate(() => JSON.stringify({...localStorage,...sessionStorage}))
  expect(stored).not.toMatch(/51\.507|-0\.128|restaurant-location/)
  await page.getByLabel('Choose a city', { exact: true }).fill('Singapore')
  await page.getByRole('button', { name: 'Search cities', exact: true }).click()
  await section.locator('.discovery-city-choices button').filter({hasText:'Singapore'}).first().click({timeout:30000})
  await expect(section.locator('.restaurant-story h3')).toBeVisible({timeout:45000})
  await expect(section.locator('.culinary-fact > a')).toBeVisible({timeout:45000})
  await expect(section.locator('.restaurant-photo > img')).toBeVisible({timeout:30000})
  await expect.poll(() => section.locator('.restaurant-photo > img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  await section.screenshot({path:'../.impeccable/review/discovery/live-singapore.png'})
  writeFileSync('../.impeccable/review/discovery/live-report.json',JSON.stringify({firstLondonRestaurant:first,singaporeRestaurant:await section.locator('.restaurant-story h3').innerText(),responses,errors},null,2))
  expect(errors).toEqual([])
})
